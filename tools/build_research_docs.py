#!/usr/bin/env python3
"""Generate docs/source-notes.md and docs/source-candidates.md from sources/registry.json and sources/facts.json.

Never edit those two docs by hand; edit sources/build_registry.py and sources/build_facts.py instead.
Run: python3 tools/build_research_docs.py
"""
import json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
reg = json.loads((ROOT / "sources/registry.json").read_text())["sources"]
facts = json.loads((ROOT / "sources/facts.json").read_text())["facts"]
by_id = {s["id"]: s for s in reg}

def esc(t): return t.replace("|", "\\|").replace("\n", " ")

out = ["# Source notes (generated)\n",
       "Generated by `tools/build_research_docs.py` from `sources/facts.json`. Do not edit by hand.\n",
       "Every row is a fact a lesson may cite. The ID is the citation key used in `docs/lessons/`. "
       "`python3 tools/verify_facts.py` re-checks each row against the raw source text, and "
       "`python3 tools/check_numbers.py` recomputes the numbers.\n"]
for mod, title in (("py", "Module A: Intro to CS and Python"), ("ml", "Module B: Intro to Machine Learning")):
    out.append(f"\n## {title}\n")
    out.append("| ID | Fact (our paraphrase) | Source | Location |\n|---|---|---|---|")
    for f in (x for x in facts if x["mod"] == mod):
        out.append(f'| {f["id"]} | {esc(f["claim"])} | {f["src"]} | {esc(f["anchor"])} |')
(ROOT / "docs/source-notes.md").write_text("\n".join(out) + "\n", encoding="utf-8")

cnt = {}
for f in facts: cnt[f["src"]] = cnt.get(f["src"], 0) + 1
out = ["# Source candidates and registry (generated)\n",
       "Generated by `tools/build_research_docs.py` from `sources/registry.json`. Do not edit by hand.\n",
       "Status `verified` means we opened and read the page (or PDF) on the access date. Only verified sources may be cited. "
       "`facts` is how many ledger facts rest on the source.\n",
       "| ID | Status | Title | Author | URL | License | Reuse | Accessed | Facts |\n|---|---|---|---|---|---|---|---|---|"]
for s in reg:
    url = s["url"]
    out.append(f'| {s["id"]} | {s["status"]} | {esc(s["title"])} | {esc(s["author"])} | {url} | {esc(s["license"])} | {esc(s["reuse"])} | {s["accessed"]} | {cnt.get(s["id"], 0)} |')
notes = [s for s in reg if s.get("notes")]
out.append("\n## Notes on individual sources\n")
for s in notes:
    out.append(f'- **{s["id"]}**: {s["notes"]}')
(ROOT / "docs/source-candidates.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"wrote docs/source-notes.md ({len(facts)} facts) and docs/source-candidates.md ({len(reg)} sources)")
