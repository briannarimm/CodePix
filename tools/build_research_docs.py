#!/usr/bin/env python3
"""Generate docs/source-notes.md and docs/source-candidates.md from sources/registry.json and sources/facts.json.

Never edit those two docs by hand; edit sources/build_registry.py and sources/build_facts.py instead.
Run: python3 tools/build_research_docs.py
"""
import json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
reg = json.loads((ROOT / "sources/registry.json").read_text())["sources"]
facts = json.loads((ROOT / "sources/facts.json").read_text())["facts"]
by_id = {s["id"]: s for s in reg}
def is_pending(f): return f.get("pending") or by_id.get(f["src"], {}).get("status") != "verified"

def esc(t): return t.replace("|", "\\|").replace("\n", " ")

out = ["# Source notes (generated)\n",
       "Generated by `tools/build_research_docs.py` from `sources/facts.json`. Do not edit by hand.\n",
       "Every row is a fact a lesson may cite. The ID is the citation key used in `docs/lessons/`. "
       "`python3 tools/verify_facts.py` re-checks each row against the raw source text, and "
       "`python3 tools/check_numbers.py` recomputes the numbers. "
       "Rows marked **PENDING** were read only through a page summary or could not be fetched as raw text; "
       "they must not be cited until `python3 tools/verify_facts.py --pending` passes on a networked machine.\n"]
for mod, title in (("py", "Module A: Intro to CS and Python"), ("ml", "Module B: Intro to Machine Learning")):
    out.append(f"\n## {title}\n")
    out.append("| ID | Fact (our paraphrase) | Source | Location |\n|---|---|---|---|")
    for f in (x for x in facts if x["mod"] == mod):
        mark = "**PENDING** " if is_pending(f) else ""
        out.append(f'| {f["id"]} | {mark}{esc(f["claim"])} | {f["src"]} | {esc(f["anchor"])} |')
(ROOT / "docs/source-notes.md").write_text("\n".join(out) + "\n", encoding="utf-8")

cnt = {}
for f in facts: cnt[f["src"]] = cnt.get(f["src"], 0) + 1
out = ["# Source candidates and registry (generated)\n",
       "Generated by `tools/build_research_docs.py` from `sources/registry.json`. Do not edit by hand.\n",
       "Status `verified` means we opened and read the page (or PDF) on the access date. Only verified sources may be cited. "
       "`facts` is how many ledger facts rest on the source.\n",
       "| ID | Status | Title | Author | URL | License | Reuse | Accessed | Facts |\n|---|---|---|---|---|---|---|---|---|"]
for s in reg:
    url = s["url"]
    out.append(f'| {s["id"]} | {s["status"]} | {esc(s["title"])} | {esc(s["author"])} | {url} | {esc(s["license"])} | {esc(s["reuse"])} | {s["accessed"]} | {cnt.get(s["id"], 0)} |')
# Level picks (primary and backup source per topic), recorded as the project notes ask. URL and license
# come from the registry, so they never drift from it.
PICKS = [
    ("A0", "Windows terminal (PowerShell)", "ms-ps-aliases", "ms-ps101-ch1", "Aliases table plus where to find PowerShell."),
    ("A0", "Definitions: computer, program, algorithm", "openstax-py-1-1", "runestone-pythonds-cs", "Algorithm from Runestone; CS50 wording is pending."),
    ("A1", "Windows install", "py-docs-windows", "vscode-python", "Python install manager; VS Code for py -3 --version."),
    ("A1", "Linux install", "pypa-linux-tools", "py-docs-unix", "PyPA page last reviewed 2021-07-26; show a checked date."),
    ("A3", "int and float", "py-docs-tutorial-intro", "openstax-py-1-5", ""),
    ("A10", "Reading errors, IndentationError", "openstax-py-1-6", "py-docs-exceptions", ""),
    ("A10", "Exceptions for troubleshooting", "py-docs-exceptions", "openstax-py-1-6", ""),
    ("A10", "Permission denied in the shell", "missing-semester-shell", "py-docs-exceptions", "Lecture suggests sudo; the book advises against it."),
    ("A13", "Package to install", "pypi-texttable", "pypi-colorama", "texttable 1.7.1, MIT, pure Python wheel."),
    ("A13", "Windows venv activation and execution policy", "py-docs-venv", "ms-ps101-ch1", ""),
    ("A-Bonus", "Install git, first commit, push", "progit-installing", "progit-remotes", "Also progit-first-time-setup, progit-getting-repo."),
    ("A-Bonus", "GitHub account and repository", "gh-docs-account", "gh-docs-repo-quickstart", "Sign-up screens change; link out."),
    ("Time machine", "Python and computing history", "py-docs-faq-general", "openstax-py-1-8", "Hopper: openstax-py-3-1. Lovelace, ENIAC, A-0 are pending."),
    ("B1", "Python needed by the ML libraries", "pypi-scikit-learn", "sk-install", "Also pypi-numpy, pypi-pandas, pypi-matplotlib."),
    ("B3", "Saving a figure", "mpl-savefig", "matplotlib-quick", ""),
    ("B4", "Regression versus classification", "sk-glossary", "mlcc-supervised", ""),
    ("B5", "Learning rate, hyperparameters", "d2l-linreg", "sk-sgd", "Google page pending (mlcc-hyperparameters)."),
    ("B8", "Majority-class baseline", "sk-metrics", "mlcc-metrics", "Dummy estimators section."),
    ("B9", "Random forests", "sk-ensemble", "gfg-types-ml", ""),
    ("B9", "Support vector machines", "sk-svm", "gfg-types-ml", ""),
    ("B12", "Backpropagation", "d2l-backprop", "sk-mlp", ""),
    ("B13", "Embeddings", "d2l-word2vec", "jm3-ch1", "Google page pending (mlcc-embeddings)."),
    ("B13", "Large language models", "d2l-pretraining", "jm3-ch7", "Google page pending (mlcc-llm)."),
    ("B14", "Semi-supervised learning", "sk-semi-supervised", "gfg-types-ml", "Second, independent source."),
]
out.append("\n## Level picks (2026-10-15)\n")
out.append("| Level | Topic | Primary | Backup | Primary URL | Primary license | Notes |\n|---|---|---|---|---|---|---|")
for lv, topic, prim, back, note in PICKS:
    ps = by_id[prim]
    out.append(f'| {lv} | {esc(topic)} | {prim} | {back} | {ps["url"]} | {esc(ps["license"])} | {esc(note)} |')
notes = [s for s in reg if s.get("notes")]
out.append("\n## Notes on individual sources\n")
for s in notes:
    out.append(f'- **{s["id"]}**: {s["notes"]}')
(ROOT / "docs/source-candidates.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"wrote docs/source-notes.md ({len(facts)} facts) and docs/source-candidates.md ({len(reg)} sources)")
