#!/usr/bin/env python3
"""Record what each turtle program in content/turtle/ draws, for the A6b replay toy.

The build machine has no screen and often no Tk, so each program runs with real Python and a
stand-in `turtle` module that writes down every move instead of drawing. The stand-in follows the
turtle module's standard mode: the turtle starts at (0, 0) facing east, left() turns counterclockwise,
and angles are in degrees. Only the calls the lesson programs use are supported; anything else fails
loudly so a program never shows a replay that skips a step.

For each content/turtle/<id>.py it writes content/turtle/<id>.json:
  {"id", "src", "python", "out", "states": [[x, y, heading, pen_down, color], ...]}
where states[0] is the start and each later entry is the state after one call.
With --write-js it also rewrites the data block between the TURTLE-DATA markers in
src/js/70-a06b-turtle.js, so the site can show the replays without a build step.
With several --python values, the first is recorded and the others must produce the same states.

Usage: python3 tools/record_turtle.py [--python PY ...] [--write-js]
"""
import argparse, json, os, pathlib, re, subprocess, sys, tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "content/turtle"
JS = ROOT / "src/js/70-a06b-turtle.js"

RUNNER = r'''
import io, json, math, sys, types
prog, outpath = sys.argv[1], sys.argv[2]
st = {"x": 0.0, "y": 0.0, "h": 0.0, "pen": True, "color": "black"}
states = []
def snap():
    states.append([round(st["x"], 2) + 0.0, round(st["y"], 2) + 0.0, round(st["h"] % 360, 2), st["pen"], st["color"]])
def forward(d):
    st["x"] += d * math.cos(math.radians(st["h"]))
    st["y"] += d * math.sin(math.radians(st["h"]))
    snap()
def back(d):
    forward(-d)
def left(a):
    st["h"] += a
    snap()
def right(a):
    left(-a)
def penup():
    st["pen"] = False
    snap()
def pendown():
    st["pen"] = True
    snap()
def color(*args):
    st["color"] = str(args[0])
    snap()
def done():
    pass
t = types.ModuleType("turtle")
for name, fn in {"forward": forward, "fd": forward, "back": back, "backward": back, "bk": back,
                 "left": left, "lt": left, "right": right, "rt": right,
                 "penup": penup, "pu": penup, "up": penup, "pendown": pendown, "pd": pendown, "down": pendown,
                 "color": color, "pencolor": color, "done": done, "mainloop": done}.items():
    setattr(t, name, fn)
def missing(name):
    raise AttributeError("the replay recorder does not support turtle." + name + " yet")
t.__getattr__ = missing
sys.modules["turtle"] = t
snap()
buf = io.StringIO()
real = sys.stdout
sys.stdout = buf
try:
    src = open(prog, encoding="utf-8").read()
    exec(compile(src, prog, "exec"), {"__name__": "__main__"})
finally:
    sys.stdout = real
with open(outpath, "w", encoding="utf-8") as f:
    json.dump({"states": states, "out": buf.getvalue()}, f)
'''


def record(py, prog):
    with tempfile.TemporaryDirectory() as tmp:
        runner = pathlib.Path(tmp, "_record.py")
        runner.write_text(RUNNER, encoding="utf-8")
        target = pathlib.Path(tmp, prog.name)
        target.write_text(prog.read_text(encoding="utf-8"), encoding="utf-8")
        env = dict(os.environ, PYTHONIOENCODING="utf-8")
        env.pop("PYTHONPATH", None)
        r = subprocess.run([py, "-I", str(runner), prog.name, "out.json"], cwd=tmp, capture_output=True, text=True, env=env, timeout=60)
        if r.returncode:
            raise SystemExit(f"FAIL {prog.stem} under {py}:\n{r.stderr[-800:]}")
        data = json.loads(pathlib.Path(tmp, "out.json").read_text(encoding="utf-8"))
        ver = subprocess.run([py, "-c", "import sys;print('%d.%d.%d' % sys.version_info[:3])"], capture_output=True, text=True).stdout.strip()
        return data, ver


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--python", action="append")
    ap.add_argument("--write-js", action="store_true")
    a = ap.parse_args()
    pys = a.python or [os.environ.get("CODEPIX_PYTHON", sys.executable)]
    out = {}
    for prog in sorted(SRC.glob("*.py")):
        data, ver = record(pys[0], prog)
        for other in pys[1:]:
            d2, v2 = record(other, prog)
            if d2 != data:
                raise SystemExit(f"FAIL {prog.stem}: Python {v2} recorded different moves from Python {ver}")
        entry = {"id": prog.stem, "src": prog.read_text(encoding="utf-8"), "python": ver, "out": data["out"], "states": data["states"]}
        (SRC / f"{prog.stem}.json").write_text(json.dumps(entry, separators=(",", ":")) + "\n", encoding="utf-8")
        out[prog.stem] = entry
        print(f"ok   {prog.stem} ({len(data['states']) - 1} moves, Python {ver})")
    if a.write_js:
        js = JS.read_text(encoding="utf-8")
        block = "/* TURTLE-DATA:BEGIN (generated by tools/record_turtle.py --write-js; do not edit) */\nconst TURTLE_REPLAYS = " + json.dumps(out, separators=(",", ":")) + ";\n/* TURTLE-DATA:END */"
        new, n = re.subn(r"/\* TURTLE-DATA:BEGIN.*?/\* TURTLE-DATA:END \*/", lambda m: block, js, flags=re.S)
        if n != 1:
            raise SystemExit("could not find the TURTLE-DATA markers in " + str(JS))
        JS.write_text(new, encoding="utf-8")
        print("updated", JS.relative_to(ROOT))


if __name__ == "__main__":
    main()
